// TestNoSelfDetection is a regression test that ensures gogenfilter does NOT
// classify its own source files as generated. This was a real false positive:
// detection.go contained sqlc code pattern markers as string literals, and
// types.go/doc.go contained the oapi-codegen marker as a constant value.
func TestNoSelfDetection(t *testing.T) {
	t.Parallel()

	sourceFiles := []string{
		"detection.go",
		"types.go",
		"doc.go",
		"sqlc.go",
		"filter.go",
		"errors.go",
		"scan.go",
		"pattern.go",
		"project.go",
	}

	for _, file := range sourceFiles {
		t.Run(file, func(t *testing.T) {
			t.Parallel()

			content, err := os.ReadFile(file) //nolint:gosec // test fixture path
			if err != nil {
				t.Skipf("cannot read %s: %v", file, err)

				return
			}

			reason := DetectReason(file, string(content), FilterAll)
			if reason != ReasonNotFiltered {
				t.Errorf("gogenfilter self-detected %s as %s; should be not-filtered", file, reason)
			}
		})
	}
}

// TestHeaderContent verifies the headerContent helper extracts content
// before the package clause correctly.
func TestHeaderContent(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name     string
		content  string
		expected string
	}{
		{
			name:     "header before package",
			content:  "// Code generated by sqlc. DO NOT EDIT.\npackage db\n",
			expected: "// Code generated by sqlc. DO NOT EDIT.",
		},
		{
			name:     "no header (starts with package)",
			content:  "package main\nfunc main() {}\n",
			expected: "",
		},
		{
			name:     "build tags before header",
			content:  "//go:build !ignore\n\npackage main\n",
			expected: "//go:build !ignore\n",
		},
		{
			name:     "no package clause",
			content:  "// just a comment\n",
			expected: "// just a comment\n",
		},
		{
			name:     "empty content",
			content:  "",
			expected: "",
		},
		{
			name:     "CRLF line endings",
			content:  "// Code generated by sqlc. DO NOT EDIT.\r\npackage db\r\n",
			expected: "// Code generated by sqlc. DO NOT EDIT.\r",
		},
		{
			name:     "package word in comment is not package clause",
			content:  "// this is not a package declaration\npackage main\n",
			expected: "// this is not a package declaration",
		},
		{
			name:     "multiple header lines",
			content:  "// Line 1\n// Line 2\npackage main\n",
			expected: "// Line 1\n// Line 2",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			got := headerContent(tc.content)
			if got != tc.expected {
				t.Errorf("headerContent() = %q, want %q", got, tc.expected)
			}
		})
	}
}
